/**
 * 受控谓词词表 + 句子级关系抽取（ADR-007）。
 *
 * 目的：在**不依赖大模型**的前提下，把「实体—实体」的语义关系从正文里抽出来，
 * 补上共现边缺失的方向与谓词。这里刻意把关系收成一个**闭集**（{@link PREDICATE_RULES}），
 * 原因有三：
 *
 * 1. 可解释：每条边都能回溯到「哪句话、哪个触发词」，出问题时能定位到规则而不是模型；
 * 2. 可复算：同一份正文、同一版规则，必然得到同一批边（没有采样、没有随机性）；
 * 3. 可评测：谓词闭集意味着可以用固定标注集衡量准确率，而不是靠肉眼感觉「图谱变好了」。
 *
 * 抽取粒度是**句子**：只在同一句内、且两个实体之间的间隔不超过 `maxGap` 时判定，
 * 跨句一律不猜（个人知识库里的错误边比缺失边更难收拾）。宁缺勿滥是本模块的第一原则。
 */

export interface PredicateRuleDefinition {
  /** 受控谓词，落库为 `relationships.relation_type` */
  relation: string
  /** 中文展示名（UI / 文档用） */
  label: string
  /** 正向触发词：左实体 → 右实体 */
  forward: string[]
  /** 反向触发词：右实体 → 左实体（被动式 / 介词式） */
  reverse: string[]
}

