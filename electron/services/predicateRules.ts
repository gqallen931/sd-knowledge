export const PREDICATE_LABELS: Record<string, string> = PREDICATE_RULES.reduce(
  (acc, rule) => { acc[rule.relation] = rule.label; return acc },
  {} as Record<string, string>,
)

/** 规则边可被重算清理的全部谓词类型（人工创建的边不在其中，永不被误删） */
export const PREDICATE_TYPES: string[] = PREDICATE_RULES.map((rule) => rule.relation)

/**
 * 全部触发词（小写）。
 *
 * 供实体化阶段排除谓词本身：TF-IDF 关键词天然会把「依赖」「生成」这类高频动词排到前面，
 * 一旦它们被当成概念实体，抽取时谓词就变成了实体之间的空白，`A 依赖 B` 反而抽不出边。
 */
export const PREDICATE_TRIGGERS: Set<string> = new Set(
  PREDICATE_RULES.flatMap(rule => [...rule.forward, ...rule.reverse]).map(trigger => trigger.toLowerCase()),
)

export interface PredicateEntityInput {
  name: string
  type: string
}

export interface PredicateEdge {
  sourceName: string
  sourceType: string
  targetName: string
  targetType: string
  relation: string
  /** 置信度，落在 (0, 0.95]，直接作为 `relationships.weight` */
  weight: number
  /** 命中触发词所在句子（截断后用于人工核对） */
  sentence: string
  /** 命中片段：两个实体之间的文本 */
  evidence: string
}

export interface PredicateExtractOptions {
  /** 两实体之间的最大字符间隔，超出即视为跨子句 */
  maxGap?: number
  /** 单句参与判定的实体上限，防止长句组合爆炸 */
  maxEntitiesPerSentence?: number
  /** 低于该置信度的边直接丢弃 */
  minWeight?: number
}

const DEFAULT_MAX_GAP = 24
const DEFAULT_MAX_ENTITIES = 6
const DEFAULT_MIN_WEIGHT = 0.55
const MAX_SENTENCE_CHARS = 600
const NEGATIONS = ['不', '未', '没有', '无', '并非', 'not ', "n't", 'never ']

interface LocatedEntity {
  name: string
  type: string
  start: number
  end: number
}

interface Sentence {
  text: string
  start: number
}

function isSentenceTerminator(ch: string, text: string, index: number): boolean {
  if (ch === '。' || ch === '！' || ch === '？' || ch === '；' || ch === '!' || ch === '?' || ch === ';' || ch === '\n') return true
  if (ch !== '.') return false
  // 英文句点：后面必须是空白/结尾，且前一个字符不是数字，避免把 "3.5" 当作句末
  const prev = index > 0 ? text[index - 1] : ''
  const next = index + 1 < text.length ? text[index + 1] : ''
  if (/\d/.test(prev)) return false
  return next === '' || /\s/.test(next)
}

function splitSentences(text: string): Sentence[] {
  const sentences: Sentence[] = []
  let start = 0
  for (let i = 0; i < text.length; i++) {
    if (!isSentenceTerminator(text[i], text, i)) continue
    const raw = text.slice(start, i + 1)
    if (raw.trim()) sentences.push({ text: raw, start })
    start = i + 1
  }
  if (start < text.length) {
    const raw = text.slice(start)
    if (raw.trim()) sentences.push({ text: raw, start })
  }
  return sentences
}

function isAsciiWord(name: string): boolean {
  return /^[A-Za-z0-9][A-Za-z0-9 ._\-/&]*$/.test(name)
}

function hasWordBoundary(sentence: string, start: number, length: number): boolean {
  const before = start > 0 ? sentence[start - 1] : ''
  const after = start + length < sentence.length ? sentence[start + length] : ''
  const isWordChar = (ch: string) => /[A-Za-z0-9_]/.test(ch)
  if (before && isWordChar(before)) return false
  if (after && isWordChar(after)) return false
  return true
}

/**
 * 在句中定位实体出现位置。
 *
 * 按**名字长度降序**扫描并占用字符区间，保证「混合检索」不会被更短的「检索」吃掉；
 * 英文实体要求词边界，避免 `API` 命中 `APIs`。同名不同类型的实体只保留第一个类型，
 * 因为从句面本身无法区分类型。
 */
function locateEntities(sentence: string, entities: PredicateEntityInput[]): LocatedEntity[] {
  const byName = new Map<string, PredicateEntityInput>()
  for (const entity of entities) {
    if (!entity.name || entity.name.length < 2) continue
    if (!byName.has(entity.name)) byName.set(entity.name, entity)
  }
  const sorted = Array.from(byName.values()).sort((a, b) => b.name.length - a.name.length)
  const taken: boolean[] = new Array(sentence.length).fill(false)
  const located: LocatedEntity[] = []

  for (const entity of sorted) {
    const needle = entity.name
    let from = 0
    while (from <= sentence.length - needle.length) {
      const idx = sentence.indexOf(needle, from)
      if (idx < 0) break
      from = idx + 1
      if (isAsciiWord(needle) && !hasWordBoundary(sentence, idx, needle.length)) continue
      let overlap = false
      for (let i = idx; i < idx + needle.length; i++) {
        if (taken[i]) { overlap = true; break }
      }
      if (overlap) continue
      for (let i = idx; i < idx + needle.length; i++) taken[i] = true
      located.push({ name: needle, type: entity.type, start: idx, end: idx + needle.length })
    }
  }
  return located.sort((a, b) => a.start - b.start)
}

function isNegated(fragment: string, trigger: string): boolean {
  const lower = fragment.toLowerCase()
  const at = lower.indexOf(trigger.toLowerCase())
  if (at < 0) return false
  const window = lower.slice(Math.max(0, at - 3), at)
  return NEGATIONS.some((negation) => window.includes(negation))
}

/**
 * 在片段中挑选最匹配的触发词。
 * 取**最长命中**：既能让 `依赖于` 优先于 `依赖`，也避免短词掩盖更精确的表述。
 */
function matchTrigger(fragment: string, triggers: string[]): string | null {
  const lower = fragment.toLowerCase()
  let best: string | null = null
  for (const trigger of triggers) {
    const needle = trigger.toLowerCase()
    if (!lower.includes(needle)) continue
    if (isNegated(fragment, trigger)) continue
    if (!best || needle.length > best.length) best = trigger
  }
  return best
}

function scoreEdge(gap: number, trigger: string, sameSentence: boolean): number {
  let weight = 0.5
  if (gap <= 8) weight += 0.2
  else if (gap <= 16) weight += 0.1
  else weight += 0.05
  if (trigger.length >= 3) weight += 0.05
  if (!sameSentence) weight -= 0.2
  return Math.min(0.95, Math.max(0.05, Number(weight.toFixed(2))))
}

/**
 * 从正文中抽取实体—实体语义边。
 *
 * 判定只发生在**同一句**内：取相邻两个实体之间的文本作为判定窗口，
 * 命中 `forward` 记为「左 → 右」，命中 `reverse` 记为「右 → 左」。
 * 结果按 `source|relation|target` 去重，保留置信度最高的一次命中。
 */
export function extractPredicateEdges(
  text: string,
  entities: PredicateEntityInput[],
  options: PredicateExtractOptions = {},
): PredicateEdge[] {
  if (!text || entities.length < 2) return []
  const maxGap = options.maxGap ?? DEFAULT_MAX_GAP
  const maxEntities = options.maxEntitiesPerSentence ?? DEFAULT_MAX_ENTITIES
  const minWeight = options.minWeight ?? DEFAULT_MIN_WEIGHT

  const best = new Map<string, PredicateEdge>()
  const offer = (edge: PredicateEdge) => {
    if (edge.weight < minWeight) return
    const key = `${edge.sourceName}|${edge.relation}|${edge.targetName}`
    const existing = best.get(key)
    if (!existing || edge.weight > existing.weight) best.set(key, edge)
  }

  for (const sentence of splitSentences(text)) {
    if (sentence.text.length > MAX_SENTENCE_CHARS) continue
    const located = locateEntities(sentence.text, entities)
    if (located.length < 2) continue

    const window = located.slice(0, maxEntities)
    // 只判定**相邻**实体对。片段里如果还夹着第三个实体，这个动词属于句子的谓语，
    // 不能同时归给两端——「向量｜检索依赖嵌入｜模型」会凭空造出「向量依赖模型」。
    // 真实语料里 jieba 把复合词切成「向量」「检索」，这条约束直接决定了边是否可用。
    for (let i = 0; i < window.length - 1; i++) {
      const left = window[i]
      const right = window[i + 1]
      const gap = right.start - left.end
      if (gap < 0 || gap > maxGap) continue
      const fragment = sentence.text.slice(left.end, right.start).trim()
      if (!fragment) continue

      for (const rule of PREDICATE_RULES) {
        const reverseTrigger = matchTrigger(fragment, rule.reverse)
        if (reverseTrigger) {
          offer({
            sourceName: right.name,
            sourceType: right.type,
            targetName: left.name,
            targetType: left.type,
            relation: rule.relation,
            weight: scoreEdge(gap, reverseTrigger, true),
            sentence: sentence.text.trim().slice(0, 240),
            evidence: fragment.slice(0, 80),
          })
          continue
        }
        const forwardTrigger = matchTrigger(fragment, rule.forward)
        if (!forwardTrigger) continue
        offer({
          sourceName: left.name,
          sourceType: left.type,
          targetName: right.name,
          targetType: right.type,
          relation: rule.relation,
          weight: scoreEdge(gap, forwardTrigger, true),
          sentence: sentence.text.trim().slice(0, 240),
          evidence: fragment.slice(0, 80),
        })
      }
    }
  }

  return Array.from(best.values()).sort(
    (a, b) => b.weight - a.weight || a.sourceName.localeCompare(b.sourceName) || a.targetName.localeCompare(b.targetName),
  )
}
